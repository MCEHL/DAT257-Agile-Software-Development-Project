package com.example.whetherapp;

import org.json.JSONArray;
import org.json.JSONObject;
import org.json.JSONException;
import java.time.*;
import java.util.ArrayList;

/**
 * Holds the parsed weather forecast for a single day.
 * On construction, rain, sun, and cloud data are derived from the raw timeseries JSON.
 */
public class DayForecast {

    // -- Practical data --
    private final LocalDate date;
    private final LocalDateTime forecastCreated;
    private final double stationLongitude, stationLatitude;
    private final JSONArray todaysTimeseries;

    // -- Weather data --
    /** True if precipitation is expected at any point during the day. */
    private boolean rainy;
    /** True if the sky is clear or nearly clear at any point during the day. */
    private boolean sunny;
    /** True if variable, half-clear, cloudy, or overcast conditions occur at any point during the day. */
    private boolean cloudy;
    private double minAmountRain, maxAmountRain;
    private double averageCloudiness;

    /**
     * Creates a forecast for the given day and immediately derives weather conditions
     * from the timeseries data.
     *
     * @param date               the date this forecast covers
     * @param forecastCreated    when the forecast was generated by SMHI
     * @param stationLongitude   longitude of the weather station
     * @param stationLatitude    latitude of the weather station
     * @param todaysTimeseries   the raw JSON timeseries entries for the day
     */
    public DayForecast(LocalDate date, LocalDateTime forecastCreated, double stationLongitude, double stationLatitude, JSONArray todaysTimeseries) {
        this.date = date;
        this.forecastCreated = forecastCreated;
        this.stationLongitude = stationLongitude;
        this.stationLatitude = stationLatitude;
        this.todaysTimeseries = todaysTimeseries;

        updateRain();
        updateClouds();
        updateSun();
    }

    /**
     * Reads precipitation data from the timeseries and updates
     * {@code minAmountRain}, {@code maxAmountRain}, and {@code rainy}.
     */
    public void updateRain() {
        try {
            for (int i = 0; i < this.todaysTimeseries.length(); i++) {
                JSONObject data = this.todaysTimeseries.getJSONObject(i).getJSONObject("data");
                this.maxAmountRain += data.getDouble("precipitation_amount_max");
                this.minAmountRain += data.getDouble("precipitation_amount_min");
            }
            this.setRainy(this.maxAmountRain > 0);
        } catch (JSONException e) {
            e.printStackTrace();
        }
    }

    /**
     * Reads symbol codes from the timeseries and sets {@code sunny} to true
     * if any entry represents a clear or nearly clear sky.
     */
    public void updateSun() {
        ArrayList<Integer> types = new ArrayList<>();
        try {
            for (int i = 0; i < this.todaysTimeseries.length(); i++) {
                JSONObject data = this.todaysTimeseries.getJSONObject(i).getJSONObject("data");
                types.add(data.getInt("symbol_code"));
            }
        } catch (JSONException e) {
            e.printStackTrace();
        }

        this.setSunny(types.contains(WeatherTypes.valueOf("clear_sky").ordinal()) ||
                types.contains(WeatherTypes.valueOf("nearly_clear_sky").ordinal()));
    }

    /**
     * Reads symbol codes and cloud area fractions from the timeseries.
     * Sets {@code cloudy} to true if any entry represents cloudy conditions,
     * and calculates {@code averageCloudiness} across all entries that report it.
     */
    public void updateClouds() {
        double totalCloudiness = 0;
        int count = 0;
        ArrayList<Integer> types = new ArrayList<>();

        try {
            for (int i = 0; i < this.todaysTimeseries.length(); i++) {
                JSONObject data = this.todaysTimeseries.getJSONObject(i).getJSONObject("data");
                types.add(data.getInt("symbol_code"));

                if (data.has("cloud_area_fraction")) {
                    totalCloudiness += data.getDouble("cloud_area_fraction");
                    count++;
                }
            }
        } catch (JSONException e) {
            e.printStackTrace();
        }

        this.setCloudy(types.contains(WeatherTypes.valueOf("variable_cloudiness").ordinal()) ||
                types.contains(WeatherTypes.valueOf("halfclear_sky").ordinal()) ||
                types.contains(WeatherTypes.valueOf("cloudy_sky").ordinal()) ||
                types.contains(WeatherTypes.valueOf("overcast").ordinal()));

        if (count > 0) {
            averageCloudiness = totalCloudiness / count;
        }
    }

    /**
     * Determines the general weather type based on the daily forecast.
     *
     * <p>Returns "rain" if precipitation is expected,
     * "cloudy" if the forecast indicates cloudy conditions,
     * or "sun" otherwise. Rain takes priority over cloudiness.</p>
     *
     * @return the weather type as "rain", "cloudy", or "sun"
     */
    public String getWeatherType() {

        if (rainy){
            return "rain";
        }
        if (cloudy) {
            return "cloudy";
        }
        return "sun";
    }

    /** @return the date this forecast covers */
    public LocalDate getDate() {
        return date;
    }

    /** @return the average cloud area fraction (0–1) across all timeseries entries that reported it */
    public double getAverageCloudiness() {
        return averageCloudiness;
    }

    /** @return true if precipitation is expected at any point during the day */
    public boolean getRainy() {
        return rainy;
    }

    /** @param rainy true if precipitation is expected */
    public void setRainy(boolean rainy) {
        this.rainy = rainy;
    }

    /** @return the summed minimum precipitation amount across all timeseries entries (mm) */
    public double getMinAmountRain() {
        return minAmountRain;
    }

    /** @param minAmountRain the summed minimum precipitation amount (mm) */
    public void setMinAmountRain(double minAmountRain) {
        this.minAmountRain = minAmountRain;
    }

    /** @return the summed maximum precipitation amount across all timeseries entries (mm) */
    public double getMaxAmountRain() {
        return maxAmountRain;
    }

    /** @param maxAmountRain the summed maximum precipitation amount (mm) */
    public void setMaxAmountRain(double maxAmountRain) {
        this.maxAmountRain = maxAmountRain;
    }

    /** @return true if a clear or nearly clear sky occurs at any point during the day */
    public boolean getSunny() {
        return sunny;
    }

    /** @param sunny true if a clear or nearly clear sky occurs */
    public void setSunny(boolean sunny) {
        this.sunny = sunny;
    }

    /** @return true if cloudy conditions occur at any point during the day */
    public boolean getCloudy() {
        return cloudy;
    }

    /** @param cloudy true if cloudy conditions occur */
    public void setCloudy(boolean cloudy) {
        this.cloudy = cloudy;
    }

    @Override
    public String toString() {
        return "Forecast for: " + this.date + ", created on: " + this.forecastCreated + ",\n" +
                "by station located at: longitude - " + this.stationLongitude + ", latitude - " + this.stationLatitude + "\n" +
                "it will rain today: " + this.rainy +
                "\nminimum amount of rain: " + this.minAmountRain + ", maximum amount of rain: " + this.maxAmountRain;
    }
}